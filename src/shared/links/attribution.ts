// kernelCAD attribution — the ONE place that names the project and links back
// to it. Exported files (STEP / GLB / STL / DXF / URDF / SRDF / SDF / MJCF)
// stamp `attributionGenerator()` into the format's own metadata field (never
// into geometry), and the public viewer surfaces link back through
// `attributionUrl()`.
//
// Edit the constants below to rename or re-point attribution. See ATTRIBUTION.md.

import { kernelcadVersion } from '../runtime/kernelcadVersion';

/** Product name as it appears in file metadata and the viewer badge. */
export const KERNELCAD_NAME = 'CrispCAD';

/** Project homepage. Attribution links and file metadata point here. */
export const KERNELCAD_HOMEPAGE = 'https://github.com/CrispStrobe/kernelCAD-web';

/** CrispCAD has no hosted app; app links resolve to the project page. */
export const KERNELCAD_APP_URL = KERNELCAD_HOMEPAGE;

/**
 * Where a link or an exported file is shown to a person or an agent. Used as
 * `utm_medium` / `ref` on project links.
 */
export type LinkSurface =
  | 'bom'
  | 'part'
  | 'studio'
  | 'embed'
  | 'embed-remix'
  | 'share'
  | 'drawing'
  | 'export';

/**
 * The generator string stamped into exported-file metadata:
 * `CrispCAD <version> (https://github.com/CrispStrobe/kernelCAD-web)`.
 *
 * `version` defaults to the runtime registry (`'unknown'` in a browser that
 * never installs it). Writers that already resolve the package version pass
 * it in.
 */
export function attributionGenerator(version: string = kernelcadVersion()): string {
  return `${KERNELCAD_NAME} ${version} (${KERNELCAD_HOMEPAGE})`;
}

/**
 * A link to one of OUR OWN pages, tagged with the surface it was shown on:
 * `?ref=<surface>&utm_source=crispcad&utm_medium=<surface>`.
 *
 * Only for CrispCAD-owned URLs. Existing query parameters and the fragment are kept;
 * calling it twice gives the same URL.
 */
export function attributionUrl(
  surface: LinkSurface,
  base: string = KERNELCAD_HOMEPAGE,
): string {
  let url: URL;
  try {
    url = new URL(base);
  } catch {
    return base;
  }
  url.searchParams.set('ref', surface);
  url.searchParams.set('utm_source', 'crispcad');
  url.searchParams.set('utm_medium', surface);
  return url.toString();
}

/**
 * App link that opens a project and starts its remix flow (sign-in first when
 * needed): `<app>/p/<slug>?remix=1`, tagged `ref=embed-remix`.
 */
export function remixUrl(slug: string): string {
  return attributionUrl('embed-remix', `${KERNELCAD_APP_URL}/p/${encodeURIComponent(slug)}?remix=1`);
}

/**
 * XML comment naming the generator, for the line after the XML declaration of
 * URDF / SRDF / SDF / MJCF output: `<!-- Generated by CrispCAD <v> (<url>) -->`.
 */
export function xmlAttributionComment(version?: string): string {
  // `--` is not allowed inside an XML comment.
  return `<!-- Generated by ${attributionGenerator(version).replace(/--/g, '- -')} -->`;
}
